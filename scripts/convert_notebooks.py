#!/usr/bin/env python3
"""Convert source Jupyter notebooks into static portfolio pages.

Usage: python scripts/convert_notebooks.py

Only the Python standard library is required. Original .ipynb files are copied
unchanged to public/notebooks for visitors to download.
"""
from __future__ import annotations

import base64
import json
import re
import shutil
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "content" / "notebooks" / "raw"
PUBLIC_DIR = ROOT / "public" / "notebooks"
DATA_FILE = ROOT / "src" / "data" / "notebooks.ts"


def as_text(value: Any) -> str:
    if isinstance(value, list):
        return "".join(str(part) for part in value)
    return str(value or "")


def make_slug(name: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return slug or "notebook"


def first_heading(cells: list[dict[str, Any]], fallback: str) -> str:
    for cell in cells:
        if cell.get("cell_type") == "markdown":
            for line in as_text(cell.get("source")).splitlines():
                cleaned = re.sub(r"^#+\s*", "", line).strip()
                if cleaned:
                    return cleaned[:90]
    return fallback.replace("-", " ").replace("_", " ").title()


def outputs_for(cell: dict[str, Any], slug: str, cell_index: int) -> list[dict[str, str]]:
    results: list[dict[str, str]] = []
    for output_index, output in enumerate(cell.get("outputs", []), start=1):
        data = output.get("data", {})
        image_data = data.get("image/png")
        if image_data:
            payload = as_text(image_data)
            if payload:
                image_dir = PUBLIC_DIR / slug / "outputs"
                image_dir.mkdir(parents=True, exist_ok=True)
                image_name = f"cell-{cell_index + 1}-output-{output_index}.png"
                (image_dir / image_name).write_bytes(base64.b64decode(payload))
                results.append({"kind": "image", "src": f"/notebooks/{slug}/outputs/{image_name}"})
        text_value = output.get("text") or data.get("text/plain")
        if text_value:
            results.append({"kind": "text", "data": as_text(text_value)})
        if output.get("output_type") == "error" and output.get("traceback"):
            results.append({"kind": "text", "data": "\n".join(output["traceback"])})
    return results


def convert_notebook(path: Path, used_slugs: set[str]) -> dict[str, str]:
    slug_base = make_slug(path.stem)
    slug = slug_base
    suffix = 2
    while slug in used_slugs:
        slug = f"{slug_base}-{suffix}"
        suffix += 1
    used_slugs.add(slug)

    notebook = json.loads(path.read_text(encoding="utf-8"))
    raw_cells = notebook.get("cells", [])
    title = first_heading(raw_cells, path.stem)
    description = ""
    for cell in raw_cells:
        if cell.get("cell_type") == "markdown":
            description = re.sub(r"\s+", " ", as_text(cell.get("source"))).strip()
            if description:
                description = description[:190] + ("…" if len(description) > 190 else "")
                break

    cells = []
    for index, cell in enumerate(raw_cells):
        cell_type = cell.get("cell_type")
        if cell_type not in {"markdown", "code"}:
            continue
        converted = {"type": cell_type, "source": as_text(cell.get("source"))}
        if cell_type == "code":
            converted["executionCount"] = cell.get("execution_count")
            converted["outputs"] = outputs_for(cell, slug, index)
        cells.append(converted)

    PUBLIC_DIR.mkdir(parents=True, exist_ok=True)
    original_name = f"{slug}.ipynb"
    shutil.copy2(path, PUBLIC_DIR / original_name)
    document = {
        "slug": slug,
        "title": title,
        "date": "",
        "cells": cells,
        "downloadUrl": f"/notebooks/{original_name}",
    }
    json_name = f"{slug}.json"
    (PUBLIC_DIR / json_name).write_text(json.dumps(document, ensure_ascii=False, indent=2), encoding="utf-8")
    return {
        "slug": slug,
        "title": title,
        "date": "",
        "description": description or "A practical notebook from the NLP course.",
        "jsonUrl": f"/notebooks/{json_name}",
        "downloadUrl": f"/notebooks/{original_name}",
    }


def main() -> None:
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    PUBLIC_DIR.mkdir(parents=True, exist_ok=True)
    sources = sorted(RAW_DIR.glob("*.ipynb"))
    used_slugs: set[str] = set()
    summaries = [convert_notebook(path, used_slugs) for path in sources]
    generated = (
        "// Generated by scripts/convert_notebooks.py — do not edit by hand.\n"
        "import type { NotebookSummary } from '../types/notebook'\n\n"
        "export const notebooks: NotebookSummary[] = "
        + json.dumps(summaries, ensure_ascii=False, indent=2)
        + "\n"
    )
    DATA_FILE.write_text(generated, encoding="utf-8")
    print(f"Converted {len(summaries)} notebook(s).")
    print(f"Source: {RAW_DIR}")
    print(f"Output: {PUBLIC_DIR}")
    if not summaries:
        print("No .ipynb files found. The portfolio will show its empty state.")


if __name__ == "__main__":
    main()
